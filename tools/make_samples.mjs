/* Build js/samples.js — tiny real F-Droid APKs base64-inlined so the one-click
 * demo works with zero network access. Icons are extracted with the same
 * AXML/ARSC parsers the app uses. */
import { readFileSync, writeFileSync } from 'node:fs';
import { ZipArchive } from '../js/zip.js';
import { parseAxml, findFirst, attr, TYPE } from '../js/axml.js';
import { ResourceTable } from '../js/arsc.js';

const PICKS = [
  ['tk.al54.dev.badpixels_4.apk',      'Bad Pixels',  'XML layout inflation · gesture detector · string resources'],
  ['org.vi_server.red_screen_3.apk',   'Red Screen',  'programmatic UI · window flags · PowerManager'],
  ['com.github.mrrar.gps_locker_11.apk','GPS Locker', 'compound widgets · ActivityManager · system services'],
];

const mimeOf = (p) => ({ png: 'image/png', webp: 'image/webp', jpg: 'image/jpeg', jpeg: 'image/jpeg' }[p.split('.').pop().toLowerCase()] || 'application/octet-stream');

function iconFor(bytes) {
  const zip = ZipArchive.open(bytes);
  const man = parseAxml(await0(zip, 'AndroidManifest.xml'));
  const rt = zip.has('resources.arsc') ? new ResourceTable(await0(zip, 'resources.arsc')) : null;
  const app = findFirst(man.root, 'application');
  const a = app && attr(app, 'icon');
  if (!a || !rt) return null;
  const id = a.dataType === TYPE.REFERENCE ? a.data : null;
  const e = id !== null ? rt.get(id) : null;
  if (e && e.str && zip.has(e.str) && /\.(png|webp|jpe?g)$/i.test(e.str)) {
    const b = zip.dataSync(e.str);
    return `data:${mimeOf(e.str)};base64,${Buffer.from(b).toString('base64')}`;
  }
  for (const n of zip.order) if (/ic_launcher[^/]*\.(png|webp)$/i.test(n)) {
    const b = zip.dataSync(n);
    return `data:${mimeOf(n)};base64,${Buffer.from(b).toString('base64')}`;
  }
  return null;
}
/* sync helper — ZipArchive.data is async, but dataSync works for stored+deflate */
function await0(zip, name) { return zip.dataSync(name); }

const out = [];
for (const [file, label, note] of PICKS) {
  const bytes = readFileSync(new URL('../test/' + file, import.meta.url));
  let icon = null;
  try { icon = iconFor(bytes); } catch (e) { console.log('icon failed for', file, e.message); }
  out.push({ file, label, note, size: `${(bytes.length / 1024).toFixed(0)} KB`, icon, data: Buffer.from(bytes).toString('base64') });
  console.log(`${file}: ${(bytes.length / 1024).toFixed(1)} KB, icon=${icon ? 'ok' : 'none'}`);
}
const j = (v) => JSON.stringify(v);
let src = `/* Generated by tools/make_samples.mjs — tiny real F-Droid APKs, base64-inlined
   so the one-click demo works with no network access at all.
   These packages are distributed by F-Droid under free-software licences. */
export const SAMPLES = [\n`;
for (const o of out) {
  src += `  {\n    file: ${j(o.file)},\n    label: ${j(o.label)},\n    note: ${j(o.note)},\n    size: ${j(o.size)},\n    icon: ${j(o.icon)},\n    data: "${o.data}",\n  },\n`;
}
src += `];\n`;
writeFileSync(new URL('../js/samples.js', import.meta.url), src);
console.log('wrote js/samples.js:', (src.length / 1024).toFixed(0), 'KB');
